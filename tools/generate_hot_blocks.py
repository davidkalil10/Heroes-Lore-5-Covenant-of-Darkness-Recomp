#!/usr/bin/env python3
"""Regenerate checked-in hot ARM blocks from cpu.cpp and the reference disassembly."""
from pathlib import Path
import re

root=Path(__file__).resolve().parents[1]
source=(root/'src/core/cpu.cpp').read_text()
source=source.replace('\n#include "hot_blocks.inc"\n','\n')
decode=source[source.index('    icount++;\n    u32 cc ='):source.index('\nvoid Cpu::run()')].rstrip()
# This is the exact interpreter decoder, specialized by the C++ compiler to
# constant PC/opcode pairs. No independently reimplemented ARM semantics.
out=['// Generated by tools/generate_hot_blocks.py from the interpreter. Do not hand edit.',
     'template<u32 pc, u32 ins>\ninline __attribute__((always_inline)) void Cpu::hotStep() {',decode]
asm=(root/'reference/libHeroesLore5.asm').read_text(encoding='utf-8')
ops={int(a,16)+0x100000:int(b,16) for a,b in re.findall(r'^\s*([0-9a-f]{5,8}): ([0-9a-f]{8})\s',asm,re.M)}
regions=[(0x150208,0x150298,0x150208),(0x156890,0x156af8,0x156aa8),(0x133f04,0x134084,0x133f04),
         (0x154bac,0x154e18,0x154dc8),(0x13be70,0x13bec8,0x13bea4),
         (0x14eba0,0x14ec38,0x14eba0),(0x151ae8,0x151b2c,0x151ae8),
         (0x153690,0x1536b4,0x153690),(0x159218,0x159438,0x159218),
         (0x1576ec,0x157914,0x1576ec),(0x1554d0,0x15560c,0x1554d0),
         (0x15a044,0x15a15c,0x15a044),(0x1a7c6c,0x1a7cbc,0x1a7c6c),(0x1b09a0,0x1b09e4,0x1b09a0)]
out+=['bool Cpu::tryHotBlock() {', 'static bool disabled = getenv("HL5_NO_AOT") != nullptr;', 'if (disabled || g_prof) return false;', 'int region=-1; switch(r[15]) {']
for i,(lo,hi,entry) in enumerate(regions):out.append(f'case 0x{entry:x}: region={i}; break;')
out+=['default: return false; }',f'static int valid[{len(regions)}]={{}};','if (!valid[region]) { bool ok=true; switch(region) {']
for i,(lo,hi,entry) in enumerate(regions):
    out.append(f'case {i}:')
    for pc in range(lo,hi+1,4):out.append(f'ok &= gm::r32(0x{pc:x}) == 0x{ops[pc]:08x}u;')
    out.append('break;')
out+=['} valid[region]=ok?1:-1; fprintf(stderr,"[aot] region=%d validated=%d\\n",region,ok); }','if(valid[region]<0) return false;',
      'const u32 entryPc=r[15];',
      f'static int checked[{len(regions)}]={{}};',
      'static const bool verifyEnabled=getenv("HL5_VERIFY_AOT")!=nullptr;',
      'const bool verify=verifyEnabled && checked[region]++<2;',
      'u32 saved[16]; bool sn=N,sz=Z,sc=C,sv=V; u64 si=icount;',
      'std::vector<u8> before; if(verify) { memcpy(saved,r,sizeof(r)); before.assign(gm::mem,gm::mem+gm::MEM_SIZE); }',
      'switch(region) {']
for i,(_,_,entry) in enumerate(regions):out.append(f'case {i}: goto L{entry:x};')
out+=['} return false;']
for lo,hi,entry in regions:
    targets={entry}
    for pc in range(lo,hi+1,4):
        ins=ops[pc]
        if (ins>>25)&7==5:
            off=(ins&0xffffff)*4
            if off&(1<<25):off-=1<<26
            targets.add(pc+8+off)
    for pc in range(lo,hi+1,4):
        ins=ops[pc]
        if pc in targets: out.append(f'L{pc:x}:')
        if (ins>>25)&7==5:
            off=(ins&0xffffff)*4
            if off & (1<<25):off-=1<<26
            target=pc+8+off; cc=ins>>28
            body='icount++; '
            dest=f'goto L{target:x};' if lo<=target<=hi else f'r[15]=0x{target:x}; goto done;'
            assert not ins&(1<<24),hex(pc)
            if cc==14:body+=dest
            else:body+=f'if(cond({cc})) {{ {dest} }}'
            out.append(body)
        else:out.append(f'hotStep<0x{pc:x},0x{ins:08x}u>();')
    out.append(f'r[15]=0x{hi+4:x}; goto done;')
out+=['done:', '''if(verify) {
    u32 result[16]; memcpy(result,r,sizeof(r)); bool en=N,ez=Z,ec=C,ev=V; u64 ei=icount;
    std::vector<u8> expected(gm::mem,gm::mem+gm::MEM_SIZE);
    memcpy(gm::mem,before.data(),gm::MEM_SIZE); memcpy(r,saved,sizeof(r)); N=sn;Z=sz;C=sc;V=sv;icount=si;
    u64 limit=0; do { step(); if(++limit>5000000) abort(); } while(r[15]!=result[15]);
    if(memcmp(r,result,sizeof(r)) || N!=en || Z!=ez || C!=ec || V!=ev || icount!=ei || memcmp(gm::mem,expected.data(),gm::MEM_SIZE)) {
        fprintf(stderr,"[aot] DIFFERENTIAL FAILURE region=%d entry=%x exit=%x\\n",region,entryPc,result[15]); abort();
    }
    fprintf(stderr,"[aot] differential PASS region=%d instructions=%llu (registers, flags, all guest memory)\\n",region,(unsigned long long)(ei-si));
}
return true;
}''']
(root/'src/core/hot_blocks.inc').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
